"""Stage 5 tests: HTML visualization of validated candidate profiles."""

import contextlib
import io
import tempfile
import unittest
from html.parser import HTMLParser
from pathlib import Path

try:
    import textx  # noqa: F401
except ImportError:  # pragma: no cover
    textx = None

EXAMPLES = Path(__file__).parent.parent / "examples"

NO_PROFILE = """candidate {
    personal { name: "Gomez <script>alert(1)</script> Addams"; }
    contact { website: www.example.com/a?b=1&c=2; }
    skills { }
    classification { none; }
}
"""


class _TextCollector(HTMLParser):
    """Collect visible text and the tags that are opened, for assertions."""

    def __init__(self):
        super().__init__()
        self.text, self.tags = [], []

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))

    def handle_data(self, data):
        if data.strip():
            self.text.append(" ".join(data.split()))


def _parse(page):
    collector = _TextCollector()
    collector.feed(page)
    return collector


@unittest.skipIf(textx is None, "textX is not installed")
class HtmlVisualizationTests(unittest.TestCase):
    def setUp(self):
        from resumelens.visualization import (
            render_html_from_dsl,
            render_html_from_resume,
        )

        self.from_dsl = render_html_from_dsl
        self.from_resume = render_html_from_resume

    def test_full_profile_shows_every_section(self):
        source = (EXAMPLES / "wednesday_addams_full.rlp").read_text(encoding="utf-8")
        page = _parse(self.from_dsl(source))
        for text in (
            "Wednesday Addams", "Candidate Profile generated by ResumeLens",
            "Personal Information", "wednesday.addams@example.com",
            "Nevermore Academy, Jericho", "Student and independent investigator",
            "Profile Summary", "Experience", "Web Application Developer",
            "Nevermore Academy Projects · 3 years",
            "Implemented backend services using Node.js.",
            "Normalized Technical Skills", "JAVASCRIPT", "GIT",
            "Qualification Evaluation", "Full Stack Developer", "ACCEPTED",
        ):
            with self.subTest(text=text):
                self.assertIn(text, page.text)
        self.assertIn(("a", {"href": "mailto:wednesday.addams@example.com"}),
                      page.tags)

    def test_one_evaluation_block_per_accepted_profile(self):
        source = (EXAMPLES / "wednesday_addams.rlp").read_text(encoding="utf-8")
        page = _parse(self.from_dsl(source))
        blocks = [t for t, a in page.tags if a.get("class") == "evaluation"]
        self.assertEqual(len(blocks), 2)
        self.assertIn("Full Stack Developer", page.text)
        self.assertIn("Data Engineer", page.text)
        self.assertEqual(page.text.count("ACCEPTED"), 2)

    def test_example_files_match_the_renderer(self):
        for name in ("wednesday_addams", "wednesday_addams_full"):
            with self.subTest(name=name):
                source = (EXAMPLES / f"{name}.rlp").read_text(encoding="utf-8")
                expected = (EXAMPLES / f"{name}.html").read_text(encoding="utf-8")
                self.assertEqual(self.from_dsl(source), expected)

    def test_no_accepted_profile_and_empty_sections(self):
        page = self.from_dsl(NO_PROFILE)
        text = _parse(page).text
        self.assertIn("NO ACCEPTED PROFILE", text)
        self.assertIn("No qualification from the catalog was recognized.", text)
        self.assertNotIn("Experience", text)
        self.assertNotIn("Education", text)
        self.assertNotIn("Profile Summary", text)

    def test_values_are_escaped(self):
        page = self.from_dsl(NO_PROFILE)
        self.assertNotIn("<script>", page)
        self.assertIn("&lt;script&gt;", page)
        self.assertIn('href="https://www.example.com/a?b=1&amp;c=2"', page)

    def test_invalid_profile_is_not_rendered(self):
        from textx.exceptions import TextXError

        with self.assertRaises(TextXError):
            self.from_dsl(NO_PROFILE.replace("none;", ""))

    def test_from_resume_runs_the_whole_pipeline(self):
        text = (
            "Mary Jane Watson\n"
            "2 years of experience developing predictive models.\n"
            "Technical Skills:\nPython, Pandas, NumPy, Scikit-learn, TensorFlow, SQL, Git.\n"
        )
        page = _parse(self.from_resume(text))
        self.assertIn("Mary Jane Watson", page.text)
        self.assertIn("Machine Learning Engineer", page.text)
        self.assertIn("2 years", page.text)


@unittest.skipIf(textx is None, "textX is not installed")
class HtmlCommandLineTests(unittest.TestCase):
    def run_cli(self, *args):
        from resumelens.cli import main

        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = main(list(args))
        return code, stdout.getvalue(), stderr.getvalue()

    def test_html_from_resume_and_from_dsl(self):
        with tempfile.TemporaryDirectory() as directory:
            resume = Path(directory, "resume.txt")
            page = Path(directory, "profile.html")
            resume.write_text(
                "Wednesday Addams\nSkills:\nJS, React.js, NodeJS, Postgres, Git.\n",
                encoding="utf-8",
            )
            code, _, _ = self.run_cli(str(resume), "--html", "-o", str(page))
            self.assertEqual(code, 0)
            self.assertIn("Full Stack Developer", page.read_text(encoding="utf-8"))

        code, out, _ = self.run_cli(
            str(EXAMPLES / "wednesday_addams.rlp"), "--validate", "--html"
        )
        self.assertEqual(code, 0)
        self.assertTrue(out.startswith("<!DOCTYPE html>"))

    def test_html_rejects_invalid_dsl(self):
        with tempfile.TemporaryDirectory() as directory:
            profile = Path(directory, "bad.rlp")
            profile.write_text("candidate { }", encoding="utf-8")
            code, out, err = self.run_cli(str(profile), "--validate", "--html")
        self.assertEqual(code, 1)
        self.assertEqual(out, "")
        self.assertIn("invalid candidate profile", err)

    def test_html_cannot_be_combined_with_dsl(self):
        with self.assertRaises(SystemExit), contextlib.redirect_stderr(io.StringIO()):
            self.run_cli(str(EXAMPLES / "wednesday_addams.txt"), "--html", "--dsl")


if __name__ == "__main__":
    unittest.main()
